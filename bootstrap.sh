#!/usr/bin/env bash
# =============================================================================
#  MJ — bootstrap.sh
#  · mj-data.json যাচাই করে
#  · file:// fallback (assets/js/mj-data.inline.js) তৈরি করে
#  · index.html-এ cache-bump (?v=তারিখ) হালনাগাদ করে
#
#  ব্যবহার:
#     chmod +x bootstrap.sh        # একবারই করতে হবে
#     ./bootstrap.sh               # ডিপ্লয়ের আগে চালান
#     ./bootstrap.sh --check       # শুধু JSON যাচাই
# =============================================================================
set -euo pipefail
cd "$(dirname "$0")"

DATA_FILE="mj-data.json"
INLINE_FILE="assets/js/mj-data.inline.js"
INDEX_FILE="index.html"
STAMP="$(date +%Y%m%d)"

[ -f "$DATA_FILE" ] || { echo "✖ $DATA_FILE পাওয়া যায়নি"; exit 1; }
command -v python3 >/dev/null || { echo "✖ python3 ইনস্টল করা প্রয়োজন"; exit 1; }

echo "→ $DATA_FILE যাচাই করা হচ্ছে…"
python3 - "$DATA_FILE" <<'PY'
import json, sys
with open(sys.argv[1], encoding="utf-8") as f:
    d = json.load(f)
missing = [k for k in ("meta", "hero", "pillars", "projects", "footer") if k not in d]
if missing:
    sys.exit("✖ অনুপস্থিত অংশ: " + ", ".join(missing))
print("✔ JSON সঠিক আছে")
print(f"  · পিলার: {len(d['pillars'].get('items', []))}টি")
print(f"  · প্রজেক্ট: {len(d['projects'].get('items', []))}টি")
print(f"  · ফুটার লিংক: {len(d['footer'].get('links', []))}টি")
PY

if [ "${1:-}" = "--check" ]; then
  echo "✔ যাচাই সম্পন্ন।"
  exit 0
fi

echo "→ inline fallback তৈরি হচ্ছে: $INLINE_FILE"
mkdir -p "$(dirname "$INLINE_FILE")"
python3 - "$DATA_FILE" "$INLINE_FILE" <<'PY'
import json, sys
with open(sys.argv[1], encoding="utf-8") as f:
    data = json.load(f)
with open(sys.argv[2], "w", encoding="utf-8") as f:
    f.write("/* Auto-generated by bootstrap.sh — সরাসরি সম্পাদনা করবেন না */\n")
    f.write("window.MJ_DATA = ")
    json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")
print("✔ তৈরি হয়েছে")
PY

echo "→ cache-bump হালনাগাদ: $INDEX_FILE (?v=$STAMP)"
python3 - "$INDEX_FILE" "$STAMP" <<'PY'
import re, sys
path, stamp = sys.argv[1], sys.argv[2]
with open(path, encoding="utf-8") as f:
    html = f.read()
for name in ("bootstrap\\.js", "mj-data\\.inline\\.js", "site\\.css"):
    html = re.sub(r"(" + name + r"\?v=)\d+", r"\g<1>" + stamp, html)
with open(path, "w", encoding="utf-8") as f:
    f.write(html)
print("✔ সম্পন্ন")
PY

echo ""
echo "✅ সব প্রস্তুত! এখন GitHub-এ পুশ করুন।"
echo "   লোকাল টেস্ট: python3 -m http.server 8000  →  http://localhost:8000"
